import numpy as np

from scipy.signal import fftconvolve

from sweep import ЧАСТОТА, ТИШИНА, ХВОСТ_ЗАПИСИ, свип, анализ, импульсная, метрики


def test_граница_находит_срез_и_не_путает_гармоники():
    эталон = свип(ЧАСТОТА)
    чистый = np.concatenate([np.zeros(ТИШИНА * ЧАСТОТА), эталон, np.zeros(ТИШИНА * ЧАСТОТА)])
    спектр = np.fft.rfft(чистый)
    спектр[np.fft.rfftfreq(чистый.size, 1 / ЧАСТОТА) > 10000] = 0
    срезанный = np.fft.irfft(спектр, чистый.size)
    запись = срезанный + 0.3 * срезанный**2 + 1e-3 * np.random.default_rng(0).standard_normal(чистый.size)
    *_, граница, _, пик = анализ(запись, эталон, ЧАСТОТА, 0.45 * ЧАСТОТА)
    assert 9000 < граница < 11000, граница
    assert abs(пик - ТИШИНА * ЧАСТОТА) < 10, пик


def test_метрики_находят_rt60_и_третью_гармонику():
    гсч = np.random.default_rng(1)
    время = np.arange(ЧАСТОТА) / ЧАСТОТА
    комната = 0.005 * гсч.standard_normal(ЧАСТОТА) * np.exp(-6.9 * время / 0.5)
    комната[0] = 1
    эталон = свип(ЧАСТОТА)
    громкий = np.concatenate([np.zeros(ТИШИНА * ЧАСТОТА), эталон + 0.4 * эталон**3, np.zeros(ХВОСТ_ЗАПИСИ * ЧАСТОТА)])
    запись = fftconvolve(громкий, комната)[: громкий.size] + 1e-6 * гсч.standard_normal(громкий.size)
    их = импульсная(запись, эталон)
    гармоники, _, rt60, _ = метрики(их, ЧАСТОТА, 0.45 * ЧАСТОТА, запись.size - эталон.size)
    assert abs(rt60 - 0.5) < 0.075, rt60
    assert abs(гармоники[1] + 32.6) < 1.5, гармоники
    assert гармоники[0] < гармоники[1] - 40, гармоники


if __name__ == "__main__":
    test_граница_находит_срез_и_не_путает_гармоники()
    test_метрики_находят_rt60_и_третью_гармонику()
    print("ok")
