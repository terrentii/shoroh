import numpy as np

from simulator import МОДУЛЯЦИИ, ПОДНЕСУЩИХ, ПРЕФИКС, ber, q_теория


def test_ber_совпадает_с_теорией():
    for название, (*_, теория) in МОДУЛЯЦИИ.items():
        for дб in (2, 6):
            симуляция, ожидание = ber(название, дб), теория(10 ** (дб / 10))
            assert abs(симуляция / ожидание - 1) < 0.15, (название, дб, симуляция, ожидание)


def test_ofdm_снимает_многолучёвость_короче_префикса():
    канал = np.zeros(ПРЕФИКС, complex)
    канал[[0, 40, 200]] = [1, 0.6j, -0.4]
    канал /= np.linalg.norm(канал)
    симуляция = ber("QPSK", 6, канал=канал), ber("OFDM", 6, канал=канал)
    ожидание = np.mean(q_теория(10**0.6 * np.abs(np.fft.fft(канал, ПОДНЕСУЩИХ)) ** 2))
    assert симуляция[0] > 0.05, симуляция
    assert abs(симуляция[1] / ожидание - 1) < 0.1, (симуляция, ожидание)


if __name__ == "__main__":
    test_ber_совпадает_с_теорией()
    test_ofdm_снимает_многолучёвость_короче_префикса()
    print("ok")
