from simulator import МОДУЛЯЦИИ, ber


def test_ber_совпадает_с_теорией():
    for название, (*_, теория) in МОДУЛЯЦИИ.items():
        for дб in (2, 6):
            симуляция, ожидание = ber(название, дб), теория(10 ** (дб / 10))
            assert abs(симуляция / ожидание - 1) < 0.15, (название, дб, симуляция, ожидание)


if __name__ == "__main__":
    test_ber_совпадает_с_теорией()
    print("ok")
